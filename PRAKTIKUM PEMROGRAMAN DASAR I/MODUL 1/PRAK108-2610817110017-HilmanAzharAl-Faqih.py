phi = 3.14
rounds = 5
distance = 14
circumference = distance / rounds
radius = circumference / (2 * phi)

print("Diketahui:")
print(f"Pak Dengklek mengelilingi taman = {rounds} putaran")
print(f"Jarak tempuh Pak Dengklek = {distance} Kilometer")
print("\nJawaban:")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah {radius:.2f} Kilometer")